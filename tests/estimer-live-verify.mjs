#!/usr/bin/env node
// ESTIMER live verification: drives the REAL Adobe engine (Illustrator
// 30.6.0, ExtendScript 4.5.6) through the COM tool
// (agent-skills/illustrator-com-automation-skill/comtool/ILLUSTRATOR_COM_TOOL.py).
//
// A probe JSX loads dist/vendor-estimer.js into the engine and runs the
// prime/now/measureUs/samples/median/stats/sleep/wrap/stopwatch vectors.
// Pure-function results (constants, medianOf, stats) are compared EXACTLY
// against the Node-side reference model (tests/vectors.ts — the same model
// npm test validates bit-for-bit in Node); timing lanes (now/measureUs/sleep/
// calibrate) are compared against tolerant bands. This is the G1-G8 live
// cross-check: the engine is the only place the real $.hiresTimer semantics
// can be observed.
//
// Exit codes: 0 = all vectors verified; 1 = assertion failures (real bug);
// 2 = SKIP — Illustrator/COM unavailable at runtime (non-failing; the
// evidence member owns engine probes, this script is the CI-safe check).
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readdirSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

var ROOT = dirname(fileURLToPath(import.meta.url));
var PROJECT = join(ROOT, '..');
var DIST = join(PROJECT, 'dist');
var VENDOR = join(DIST, 'vendor-estimer.js');
var TOOL = 'C:/Program Files/Adobe/Adobe Illustrator 2026/Presets/en_US/Scripts/agent-skills/illustrator-com-automation-skill/comtool/ILLUSTRATOR_COM_TOOL.py';

if (!existsSync(VENDOR)) {
  console.error('live-verify: build first (npm run build) - ' + VENDOR + ' missing');
  process.exit(1);
}
if (!existsSync(TOOL)) {
  console.error('live-verify: COM tool not found at ' + TOOL);
  process.exit(1);
}

// ---- Node-side reference model (same vectors npm test validates) ------------
var V_BUNDLE = join(ROOT, '.estimer-vectors.bundle.mjs');
execFileSync(process.execPath, [esbuildBin(), join(ROOT, 'vectors.ts'),
  '--bundle', '--outfile=' + V_BUNDLE,
  '--format=esm', '--platform=node', '--target=es2019',
  '--log-level=warning'], { stdio: 'inherit' });
var vecs = await import(pathToFileURL(V_BUNDLE).href);
var STATS_VECTORS = vecs.STATS_VECTORS;
var MEDIAN_VECTORS = vecs.MEDIAN_VECTORS;
var refStats = vecs.refStats;
var refMedian = vecs.refMedian;

// NaN <-> JSON null: stats/median aggregates are NaN on empty arrays, which
// JSON.stringify turns into null; normalize before comparing.
function numEq(a, b) {
  if (a === b) { return true; }
  if (typeof a === 'number' && a !== a && (b === null || b === void 0 || (typeof b === 'number' && b !== b))) { return true; }
  if (typeof b === 'number' && b !== b && (a === null || a === void 0)) { return true; }
  return false;
}

function runTool(args) {
  try {
    return execFileSync('python', [TOOL].concat(args), { encoding: 'utf8', timeout: 300000 });
  } catch (e) {
    return null;
  }
}

function skip(msg) {
  console.log('SKIP: ' + msg);
  console.log('live-verify: exit 2 (Illustrator/COM unavailable - engine probes are the evidence member\'s lane)');
  process.exit(2);
}

// ---- availability gate: status --no-launch -----------------------------------
// The tool reports COM unavailability in two shapes: a nonzero exit/!ok
// envelope (connect failure), or ok:true with `_error` markers inside the
// result fields (e.g. "No running Illustrator.Application instance"). Both
// are treated as unavailable -> SKIP (exit 2).
var statusOut = runTool(['status', '--no-launch']);
if (statusOut === null) {
  skip('Illustrator not reachable via COM (status --no-launch failed)');
}
var statusEnv;
try { statusEnv = JSON.parse(statusOut.trim()); } catch (e) { skip('status output not JSON: ' + statusOut.slice(0, 300)); }
var sv = statusEnv && statusEnv.result;
var errProbe = !!(sv && ((sv.Name && sv.Name._error) || (sv.Version && sv.Version._error) || (sv.DocumentsCount && sv.DocumentsCount._error)));
if (!statusEnv || !statusEnv.ok || !sv || errProbe) {
  skip('Illustrator/COM unavailable: ' + JSON.stringify(statusEnv).slice(0, 500));
}

// ---- emit the engine probe -----------------------------------------------------
var probeDir = join(process.env.TEMP || '', 'estimer-live');
mkdirSync(probeDir, { recursive: true });
var probePath = join(probeDir, 'estimer-live-battery.jsx');
var vendorForProbe = VENDOR.replace(/\\/g, '/');
var statsInJson = JSON.stringify(STATS_VECTORS.map(function (v) { return v.samples; }));
var medInJson = JSON.stringify(MEDIAN_VECTORS.map(function (v) { return v.values; }));

var probeSrc = [
  '#target illustrator',
  '// generated by tests/estimer-live-verify.mjs - do not edit',
  '$.evalFile(File("' + vendorForProbe + '"));',
  'var EST = $.global.ESTIMER;',
  'var report = {};',
  'report.engine = $.version;',
  'report.host = app.name + " " + app.version;',
  '',
  'report.constants = EST.constants();',
  'report.lane = EST.lane();',
  'report.describe0 = EST.describe();',
  '',
  '// prime/now/epoch (first read after prime must be tiny, NOT startup us)',
  'EST.prime();',
  'var n1 = EST.now();',
  'var e1 = EST.epoch();',
  'var nm = EST.nowMs();',
  'report.primeNow = { n1: n1, e1: e1, nm: nm };',
  '',
  '// monotonicity: 100 consecutive reads, never negative, never decreasing',
  'var seq = [];',
  'var qi;',
  'for (qi = 0; qi < 100; qi++) { seq[seq.length] = EST.now(); }',
  'report.seq = seq;',
  '',
  '// measureUs validation',
  'report.meas = {',
  '  noop: EST.measureUs(function () {}),',
  '  capped1: EST.measureUs(function () {}, 1),',
  '  wide: EST.measureUs(function () {}, 1000000000)',
  '};',
  '',
  '// samples / median-of-n / best-of-n',
  'var sp = EST.samples(9, function () {}, { warmup: 2, collectRejected: true });',
  'report.samp = { len: sp.length, vals: sp, rejected: (sp.rejected || []).length };',
  'report.med = { median9: EST.median(9, function () {}), best9: EST.best(9, function () {}) };',
  '',
  '// pure: medianOf on the shared MEDIAN_VECTORS values (engine must equal Node exactly)',
  'var medIn = ' + medInJson + ';',
  'report.medianOf = [];',
  'var mvi;',
  'for (mvi = 0; mvi < medIn.length; mvi++) {',
  '  report.medianOf[report.medianOf.length] = EST.medianOf(medIn[mvi]);',
  '}',
  '',
  '// stats: shared vectors through the engine',
  'var statsIn = ' + statsInJson + ';',
  'report.stats = [];',
  'var si;',
  'for (si = 0; si < statsIn.length; si++) {',
  '  report.stats[report.stats.length] = EST.stats(statsIn[si]);',
  '}',
  'var rv = [10, 20, 30];',
  'rv.rejected = [{ index: 0, value: -5, reason: "negative" }];',
  'report.statsRejected = EST.stats(rv);',
  '',
  '// wrap policy round-trip',
  'EST.setWrapPolicy("reject");',
  'var wp1 = EST.wrapPolicy();',
  'EST.setWrapPolicy("correct");',
  'var wp2 = EST.wrapPolicy();',
  'report.wrap = { p1: wp1, p2: wp2 };',
  '',
  '// stopwatch nesting (outer must include inner - the nesting-corruption fix)',
  'var swA = EST.stopwatch();',
  'var swB = EST.stopwatch();',
  'swA.start();',
  'swB.start();',
  'var swb = swB.stop();',
  'var swa = swA.stop();',
  'report.sw = { inner: swb, outer: swa, elapsed: swA.elapsed(), running: swA.running };',
  '',
  '// sleep: pure busy-wait (2ms) and coarse+landing lane (50ms)',
  'var t0 = EST.wallNow();',
  'var slept1 = EST.sleep(2);',
  'var t1 = EST.wallNow();',
  'var slept2 = EST.sleep(50);',
  'var t2 = EST.wallNow();',
  'report.sleep = { s1us: slept1, w1ms: t1 - t0, s2us: slept2, w2ms: t2 - t1 };',
  '',
  '// calibrate (median read overhead)',
  'report.cal = EST.calibrate();',
  'report.describe1 = EST.describe();',
  'report;'
].join('\n');
writeFileSync(probePath, probeSrc);

console.log('live-verify: running vectors in Illustrator (' + (statusEnv.result.Version || '?') + ')...');
var pyOut = runTool(['eval', '--file', probePath.replace(/\\/g, '/')]);
if (pyOut === null) {
  skip('COM eval failed - Illustrator/COM became unavailable during the run');
}
var env;
try { env = JSON.parse(pyOut.trim()); } catch (e) { skip('eval output not JSON: ' + pyOut.slice(0, 300)); }
if (!env || !env.ok || !env.result) {
  skip('tool/engine error: ' + JSON.stringify(env).slice(0, 800));
}
var report = env.result.result || env.result;

var failures = 0;
var checks = 0;
function ok(desc, cond, detail) {
  checks++;
  if (cond) { console.log('  ok   ' + desc); }
  else { failures++; console.error('  FAIL ' + desc + (detail ? ' — ' + detail : '')); }
}

// ---- pure-function comparisons (exact) ----------------------------------------
var C = report.constants;
ok('constants.MAX_VALID_US', numEq(C.MAX_VALID_US, 100000000));
ok('constants.MAX_VALID_MS', numEq(C.MAX_VALID_MS, 100000));
ok('constants.MIN_VALID_US', numEq(C.MIN_VALID_US, 0));
ok('constants.WRAP_PERIOD_US', numEq(C.WRAP_PERIOD_US, 4294967296));
ok('constants.WRAP_POINT_US', numEq(C.WRAP_POINT_US, 2147483648));
ok('constants.SLEEP_COARSE_THRESHOLD_MS', numEq(C.SLEEP_COARSE_THRESHOLD_MS, 25));

ok('lane is engine', report.lane === 'engine', 'got ' + report.lane);
ok('describe0.engine equals $.version', report.describe0.engine === report.engine);
ok('describe0.wrapPolicy correct', report.describe0.wrapPolicy === 'correct');
ok('describe0.primed false before prime', report.describe0.primed === false);
ok('describe0.reads 0 before prime', report.describe0.reads === 0);
ok('host is Illustrator', typeof report.host === 'string' && report.host.indexOf('Illustrator') >= 0, String(report.host));

// medianOf: engine vs Node reference (NaN <-> JSON null)
var medExpect = MEDIAN_VECTORS.map(function (mv) { return refMedian(mv.values); });
for (var mi = 0; mi < report.medianOf.length; mi++) {
  ok('medianOf vector ' + mi, numEq(report.medianOf[mi], medExpect[mi]),
    'engine=' + report.medianOf[mi] + ' node=' + medExpect[mi]);
}

// stats: engine vs reference model (bit-exact fields)
for (var si2 = 0; si2 < STATS_VECTORS.length; si2++) {
  var got = report.stats[si2];
  var want = refStats(STATS_VECTORS[si2].samples);
  var fields = ['count', 'min', 'max', 'mean', 'median', 'p95', 'p99', 'rejected'];
  var all = true;
  var fi = 0;
  for (fi = 0; fi < fields.length; fi++) {
    if (!numEq(got[fields[fi]], want[fields[fi]])) { all = false; }
  }
  ok('stats ' + STATS_VECTORS[si2].desc, all, JSON.stringify(got) + ' vs ' + JSON.stringify(want));
}
ok('stats rejected carry', numEq(report.statsRejected.rejected, 1) && numEq(report.statsRejected.count, 3) &&
  numEq(report.statsRejected.median, 20), JSON.stringify(report.statsRejected));

ok('wrap round-trip reject', report.wrap.p1 === 'reject');
ok('wrap round-trip correct', report.wrap.p2 === 'correct');

// ---- timing lanes (tolerant bands) ---------------------------------------------
var pn = report.primeNow;
ok('prime/now first read tiny (startup discarded)', typeof pn.n1 === 'number' && pn.n1 >= 0 && pn.n1 < 100000, 'n1=' + pn.n1);
ok('epoch close to now after prime', typeof pn.e1 === 'number' && pn.e1 >= 0 && Math.abs(pn.e1 - pn.n1) < 100000, 'e1=' + pn.e1 + ' n1=' + pn.n1);
ok('nowMs small', typeof pn.nm === 'number' && pn.nm >= 0 && pn.nm < 100, 'nm=' + pn.nm);

var seq = report.seq;
var mono = seq.length === 100;
if (mono) {
  for (var qi2 = 0; qi2 < seq.length; qi2++) {
    if (typeof seq[qi2] !== 'number' || seq[qi2] < 0 || (qi2 > 0 && seq[qi2] < seq[qi2 - 1])) { mono = false; }
  }
}
ok('100 reads monotonic non-negative', mono, 'len=' + seq.length + ' first=' + seq[0] + ' last=' + seq[seq.length - 1]);

ok('measureUs noop positive', typeof report.meas.noop === 'number' && report.meas.noop > 0 && report.meas.noop < 1000000, String(report.meas.noop));
ok('measureUs capped(1) rejects', report.meas.capped1 === null, String(report.meas.capped1));
ok('measureUs wide positive', typeof report.meas.wide === 'number' && report.meas.wide > 0 && report.meas.wide < 1000000, String(report.meas.wide));

ok('samples length 5..9', report.samp.len >= 5 && report.samp.len <= 9, 'len=' + report.samp.len);
var sampOk = true;
for (var svi = 0; svi < report.samp.vals.length; svi++) {
  if (typeof report.samp.vals[svi] !== 'number' || report.samp.vals[svi] <= 0) { sampOk = false; }
}
ok('samples all valid positives', sampOk, JSON.stringify(report.samp.vals));
ok('samples rejected count number', typeof report.samp.rejected === 'number' && report.samp.rejected >= 0, String(report.samp.rejected));

ok('median(9) positive', typeof report.med.median9 === 'number' && report.med.median9 > 0, String(report.med.median9));
ok('best(9) positive and <= median', typeof report.med.best9 === 'number' && report.med.best9 > 0 && report.med.best9 <= report.med.median9,
  'best=' + report.med.best9 + ' median=' + report.med.median9);

ok('stopwatch inner > 0', typeof report.sw.inner === 'number' && report.sw.inner > 0, String(report.sw.inner));
ok('stopwatch outer >= inner (nesting-safe)', report.sw.outer >= report.sw.inner, 'outer=' + report.sw.outer + ' inner=' + report.sw.inner);
ok('stopwatch elapsed >= outer', report.sw.elapsed >= report.sw.outer, 'elapsed=' + report.sw.elapsed);
ok('stopwatch not running', report.sw.running === false);

ok('sleep(2) pure busy-wait us', typeof report.sleep.s1us === 'number' && report.sleep.s1us >= 1000 && report.sleep.s1us <= 500000, String(report.sleep.s1us));
ok('sleep(2) wall ms', report.sleep.w1ms >= 1 && report.sleep.w1ms <= 1000, String(report.sleep.w1ms));
ok('sleep(50) coarse lane us', typeof report.sleep.s2us === 'number' && report.sleep.s2us >= 25000 && report.sleep.s2us <= 1000000, String(report.sleep.s2us));
ok('sleep(50) wall ms', report.sleep.w2ms >= 20 && report.sleep.w2ms <= 2000, String(report.sleep.w2ms));

ok('calibrate positive overhead', typeof report.cal === 'number' && report.cal > 0 && report.cal < 1000000, String(report.cal));
ok('describe1 primed true', report.describe1.primed === true);
ok('describe1 reads > 0', typeof report.describe1.reads === 'number' && report.describe1.reads > 0, String(report.describe1.reads));
ok('describe1 calibratedUs recorded', typeof report.describe1.calibratedUs === 'number' && report.describe1.calibratedUs > 0, String(report.describe1.calibratedUs));

// ---- summary ---------------------------------------------------------------------
if (failures > 0) {
  console.error('live-verify: ' + failures + ' of ' + checks + ' engine checks FAILED (engine ' + report.engine + ', ' + report.host + ')');
  process.exit(1);
}
console.log('live-verify: ' + checks + '/' + checks + ' engine checks passed (' + report.engine + ', ' + report.host + ')');

function esbuildBin() {
  var direct = join(PROJECT, 'node_modules', 'esbuild', 'bin', 'esbuild');
  if (existsSync(direct)) { return direct; }
  var cacheDirs = [
    join(process.env.LOCALAPPDATA || '', 'npm-cache', '_npx'),
    join(process.env.USERPROFILE || '', 'AppData', 'Local', 'npm-cache', '_npx')
  ];
  for (var c = 0; c < cacheDirs.length; c++) {
    try {
      var entries = readdirSync(cacheDirs[c]);
      for (var j = 0; j < entries.length; j++) {
        var p = join(cacheDirs[c], entries[j], 'node_modules', 'esbuild', 'bin', 'esbuild');
        if (existsSync(p)) { return p; }
      }
    } catch (ignore) {}
  }
  return 'npx esbuild';
}
